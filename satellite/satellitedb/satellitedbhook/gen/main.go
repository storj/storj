// gen generates hook wrappers for every interface reachable from satellite.DB.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"os"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

// wrapPrefix restricts wrapping to the satellite interfaces.
const wrapPrefix = "storj.io/storj/satellite"

func main() {
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedName | packages.NeedTypes}, "storj.io/storj/satellite")
	if err != nil {
		panic(err)
	}
	if packages.PrintErrors(pkgs) > 0 {
		os.Exit(1)
	}

	g := &generator{
		aliases:  map[string]string{},
		taken:    map[string]bool{"context": true, "reflect": true},
		wrapped:  map[*types.Named]bool{},
		wrapName: map[*types.Named]string{},
	}
	g.aliases["context"] = "context"
	g.aliases["reflect"] = "reflect"

	root := pkgs[0].Types.Scope().Lookup("DB").Type().(*types.Named)
	g.enqueue(root)
	for len(g.queue) > 0 {
		n := g.queue[0]
		g.queue = g.queue[1:]
		g.genInterface(n)
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by satellitedbhook/gen. DO NOT EDIT.\n\npackage satellitedbhook\n\nimport (\n")
	paths := make([]string, 0, len(g.aliases))
	for path := range g.aliases {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		fmt.Fprintf(&out, "\t%s %q\n", g.aliases[path], path)
	}
	out.WriteString(")\n")
	out.Write(g.body.Bytes())

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		_ = os.WriteFile("hooks.gen.go", out.Bytes(), 0644)
		panic(err)
	}
	if err := os.WriteFile("hooks.gen.go", formatted, 0644); err != nil {
		panic(err)
	}
}

type generator struct {
	aliases map[string]string // package path -> alias
	taken   map[string]bool   // aliases in use

	queue    []*types.Named
	wrapped  map[*types.Named]bool
	wrapName map[*types.Named]string

	body bytes.Buffer
}

func (g *generator) qualifier(pkg *types.Package) string {
	if alias, ok := g.aliases[pkg.Path()]; ok {
		return alias
	}
	alias := pkg.Name()
	for i := 2; g.taken[alias]; i++ {
		alias = fmt.Sprintf("%s%d", pkg.Name(), i)
	}
	g.aliases[pkg.Path()] = alias
	g.taken[alias] = true
	return alias
}

func (g *generator) typeString(t types.Type) string {
	return types.TypeString(t, g.qualifier)
}

// asWrappable returns the named interface, when values of type t should be wrapped.
func (g *generator) asWrappable(t types.Type) (*types.Named, bool) {
	n, ok := t.(*types.Named)
	if !ok || n.Obj().Pkg() == nil || !strings.HasPrefix(n.Obj().Pkg().Path(), wrapPrefix) {
		return nil, false
	}
	if _, ok := n.Underlying().(*types.Interface); !ok || n.TypeParams().Len() > 0 || !n.Obj().Exported() {
		return nil, false
	}
	if !implementable(n) {
		return nil, false
	}
	return n, true
}

// implementable checks whether the interface can be implemented outside of its package.
func implementable(n *types.Named) bool {
	iface := n.Underlying().(*types.Interface)
	for m := range iface.Methods() {
		if !m.Exported() || !exportedTypes(m.Type(), map[types.Type]bool{}) {
			return false
		}
	}
	return true
}

func exportedTypes(t types.Type, seen map[types.Type]bool) bool {
	if seen[t] {
		return true
	}
	seen[t] = true
	switch t := t.(type) {
	case *types.Named:
		if t.Obj().Pkg() != nil && !t.Obj().Exported() {
			return false
		}
		for arg := range t.TypeArgs().Types() {
			if !exportedTypes(arg, seen) {
				return false
			}
		}
		return true
	case *types.Alias:
		return exportedTypes(types.Unalias(t), seen)
	case *types.Pointer:
		return exportedTypes(t.Elem(), seen)
	case *types.Slice:
		return exportedTypes(t.Elem(), seen)
	case *types.Array:
		return exportedTypes(t.Elem(), seen)
	case *types.Map:
		return exportedTypes(t.Key(), seen) && exportedTypes(t.Elem(), seen)
	case *types.Chan:
		return exportedTypes(t.Elem(), seen)
	case *types.Signature:
		return exportedTuple(t.Params(), seen) && exportedTuple(t.Results(), seen)
	case *types.Struct:
		for field := range t.Fields() {
			if !field.Exported() || !exportedTypes(field.Type(), seen) {
				return false
			}
		}
		return true
	default:
		return true
	}
}

func exportedTuple(tuple *types.Tuple, seen map[types.Type]bool) bool {
	for v := range tuple.Variables() {
		if !exportedTypes(v.Type(), seen) {
			return false
		}
	}
	return true
}

func (g *generator) enqueue(n *types.Named) string {
	if name, ok := g.wrapName[n]; ok {
		return name
	}
	alias := g.qualifier(n.Obj().Pkg())
	name := alias + n.Obj().Name()
	g.wrapName[n] = name
	g.queue = append(g.queue, n)
	return name
}

// declaringTypes returns n and the embedded interfaces of n, which declare method.
func declaringTypes(n *types.Named, method string) []*types.Named {
	result := []*types.Named{n}
	iface := n.Underlying().(*types.Interface)
	for embedded := range iface.EmbeddedTypes() {
		e, ok := embedded.(*types.Named)
		if !ok || !e.Obj().Exported() || e.Obj().Pkg() == nil {
			continue
		}
		obj, _, _ := types.LookupFieldOrMethod(e, false, e.Obj().Pkg(), method)
		if obj != nil {
			result = append(result, declaringTypes(e, method)...)
		}
	}
	return result
}

func isContext(t types.Type) bool {
	n, ok := t.(*types.Named)
	return ok && n.Obj().Pkg() != nil && n.Obj().Pkg().Path() == "context" && n.Obj().Name() == "Context"
}

func (g *generator) genInterface(n *types.Named) {
	name := g.wrapName[n]
	typ := g.typeString(n)

	w := &g.body
	fmt.Fprintf(w, "\ntype %s struct{ inner %s }\n", name, typ)
	fmt.Fprintf(w, "\nfunc wrap%s(v %s) %s {\n", capitalize(name), typ, typ)
	fmt.Fprintf(w, "\tif v == nil {\n\t\treturn nil\n\t}\n\treturn &%s{inner: v}\n}\n", name)

	iface := n.Underlying().(*types.Interface)
	for m := range iface.Methods() {
		g.genMethod(n, name, m)
	}
}

func paramList(n int) string {
	var list []string
	for i := range n {
		list = append(list, fmt.Sprintf("p%d", i))
	}
	return strings.Join(list, ", ")
}

func capitalize(s string) string {
	return strings.ToUpper(s[:1]) + s[1:]
}

func (g *generator) genMethod(n *types.Named, name string, m *types.Func) {
	sig := m.Type().(*types.Signature)
	params, results := sig.Params(), sig.Results()

	var decl, args []string
	for i := range params.Len() {
		t := params.At(i).Type()
		typ := g.typeString(t)
		if sig.Variadic() && i == params.Len()-1 {
			typ = "..." + g.typeString(t.(*types.Slice).Elem())
			args = append(args, fmt.Sprintf("p%d...", i))
		} else {
			args = append(args, fmt.Sprintf("p%d", i))
		}
		decl = append(decl, fmt.Sprintf("p%d %s", i, typ))
	}

	var resultDecl, resultNames []string
	for i := range results.Len() {
		resultDecl = append(resultDecl, fmt.Sprintf("r%d %s", i, g.typeString(results.At(i).Type())))
		resultNames = append(resultNames, fmt.Sprintf("r%d", i))
	}

	w := &g.body
	fmt.Fprintf(w, "\nfunc (w *%s) %s(%s) (%s) {\n", name, m.Name(), strings.Join(decl, ", "), strings.Join(resultDecl, ", "))

	hookable := params.Len() > 0 && isContext(params.At(0).Type())
	returnsErr := results.Len() > 0 && types.Identical(results.At(results.Len()-1).Type(), types.Universe.Lookup("error").Type())
	var ifaces string
	if hookable {
		var list []string
		for _, d := range declaringTypes(n, m.Name()) {
			list = append(list, fmt.Sprintf("reflect.TypeFor[%s]()", g.typeString(d)))
		}
		ifaces = strings.Join(list, ", ")

		fmt.Fprintf(w, "\tif hasHooks(p0) {\n")
		fmt.Fprintf(w, "\t\tif err := callBefore(p0, %q, []any{%s}, %s); err != nil {\n", m.Name(), paramList(params.Len()), ifaces)
		if returnsErr {
			fmt.Fprintf(w, "\t\t\tr%d = err\n\t\t\treturn\n", results.Len()-1)
		} else {
			fmt.Fprintf(w, "\t\t\tpanic(err)\n")
		}
		fmt.Fprintf(w, "\t\t}\n\t}\n")
	}

	// wrap callbacks, which receive wrappable interfaces.
	for i := range params.Len() {
		cb, ok := params.At(i).Type().(*types.Signature)
		if !ok || cb.Variadic() {
			continue
		}
		var cbDecl, cbArgs []string
		needsWrap := false
		for k := range cb.Params().Len() {
			t := cb.Params().At(k).Type()
			cbDecl = append(cbDecl, fmt.Sprintf("a%d %s", k, g.typeString(t)))
			if wn, ok := g.asWrappable(t); ok {
				cbArgs = append(cbArgs, fmt.Sprintf("wrap%s(a%d)", capitalize(g.enqueue(wn)), k))
				needsWrap = true
			} else {
				cbArgs = append(cbArgs, fmt.Sprintf("a%d", k))
			}
		}
		if !needsWrap {
			continue
		}
		cbResults := ""
		if cb.Results().Len() > 0 {
			cbResults = g.typeString(cb.Results())
		}
		fmt.Fprintf(w, "\tif p%d != nil {\n\t\tfn := p%d\n", i, i)
		fmt.Fprintf(w, "\t\tp%d = func(%s) %s {\n\t\t\treturn fn(%s)\n\t\t}\n\t}\n", i, strings.Join(cbDecl, ", "), cbResults, strings.Join(cbArgs, ", "))
	}

	call := fmt.Sprintf("w.inner.%s(%s)", m.Name(), strings.Join(args, ", "))
	if results.Len() == 0 {
		fmt.Fprintf(w, "\t%s\n", call)
	} else {
		fmt.Fprintf(w, "\t%s = %s\n", strings.Join(resultNames, ", "), call)
	}
	for i := range results.Len() {
		if wn, ok := g.asWrappable(results.At(i).Type()); ok {
			fmt.Fprintf(w, "\tr%d = wrap%s(r%d)\n", i, capitalize(g.enqueue(wn)), i)
		}
	}
	if hookable {
		after := fmt.Sprintf("callAfter(p0, %q, []any{%s}, []any{%s}, %t, %s)",
			m.Name(), paramList(params.Len()), strings.Join(resultNames, ", "), returnsErr, ifaces)
		if returnsErr {
			fmt.Fprintf(w, "\tif hasHooks(p0) {\n\t\tr%d = %s\n\t}\n", results.Len()-1, after)
		} else {
			fmt.Fprintf(w, "\tif hasHooks(p0) {\n\t\t_ = %s\n\t}\n", after)
		}
	}
	fmt.Fprintf(w, "\treturn\n}\n")
}
